/*
 * Offline service worker (brief §Phase 2.7): cache-first for the app shell
 * and static assets, network-only for /api (freshness is the product — the
 * app layer shows localStorage last-known data with an offline badge
 * instead of silently serving stale API responses).
 */
const CACHE = "cyberekt-shell-v1";
const SHELL = ["/", "/signals", "/performance", "/reports", "/learn", "/manifest.webmanifest", "/icon.svg"];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const url = new URL(event.request.url);
  if (event.request.method !== "GET" || url.origin !== self.location.origin) return;
  if (url.pathname.startsWith("/api/")) return; // never cache market data here

  event.respondWith(
    caches.match(event.request).then((cached) => {
      const fetched = fetch(event.request)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((cache) => cache.put(event.request, copy));
          }
          return res;
        })
        .catch(() => cached ?? caches.match("/"));
      return cached ?? fetched;
    })
  );
});
